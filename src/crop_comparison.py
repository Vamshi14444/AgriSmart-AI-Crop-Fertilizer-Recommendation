def get_all_crop_names() -> list[str]:
    """Return sorted list of canonical crop identifiers."""
    return sorted(CROP_PROFILES.keys())


def get_crop_profile(crop_id: str) -> dict:
    """Return profile dictionary for a crop."""
    return CROP_PROFILES.get(crop_id.lower().strip(), {})


def compare_two_crops(crop_a_id: str, crop_b_id: str) -> pd.DataFrame:
    """
    Generate a formatted side-by-side comparison table for two crops.
    """
    p_a = get_crop_profile(crop_a_id)
    p_b = get_crop_profile(crop_b_id)

    metrics = [
        ("Common & Botanical Name", "name"),
        ("Crop Category", "category"),
        ("Growth Duration", "duration_days"),
        ("Water Need (Quantitative)", "water_req_mm"),
        ("Water Intensity", "water_level"),
        ("Nitrogen (N) Demand", "n_demand"),
        ("Phosphorus (P) Demand", "p_demand"),
        ("Potassium (K) Demand", "k_demand"),
        ("Thermal Window", "temp_range"),
        ("Optimal pH Index", "ph_range"),
        ("Ideal Soil Texture", "soil_types"),
        ("Drought Tolerance", "drought_tolerance"),
        ("Atmospheric N Fixation", "nitrogen_fixing"),
        ("Market & Economic Risk", "market_risk"),
        ("Eco-Agronomic Benefit", "ecological_benefit"),
    ]

    rows = []
    for label, key in metrics:
        val_a = p_a.get(key, "N/A")
        val_b = p_b.get(key, "N/A")
        if isinstance(val_a, bool):
            val_a = "✅ Yes (Fixes Atmospheric N)" if val_a else "❌ No"
        if isinstance(val_b, bool):
            val_b = "✅ Yes (Fixes Atmospheric N)" if val_b else "❌ No"
        rows.append({
            "Agronomic Dimension": label,
            f"🌾 {p_a.get('name', crop_a_id.title())}": str(val_a),
            f"🌱 {p_b.get('name', crop_b_id.title())}": str(val_b),
        })

    return pd.DataFrame(rows).set_index("Agronomic Dimension")
